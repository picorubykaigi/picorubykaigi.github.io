  const t_orig=()=>songT(MEL62);
  // 71 — やわらか/オルゴール: 全声部を三角波に。角が取れて丸い
  const t_soft=()=>songT(MEL62,{lead:'triangle',harm:'triangle',bass:'triangle',vib:0.006});
  // 72 — ファミコン強: ビブラート深め＋最後にノイズの「シャッ」。チップらしさ増
  const t_fc=()=>songT(MEL62,{vib:0.02,endSparkle:true});

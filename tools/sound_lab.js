  const s61=()=>song([...HEAD50,
    ['A6',0.72,0.15,'F'],['B6',0.88,0.15,'G'],['C7',1.04,0.46,'C']]);

  // 62 — 確定メロディ/ハーモニー: 7音等間隔で溜めなく流す(たたたたたたた)
  //   ド↑ソ・ラ ファ ・ソ ラ ド / 和声 C-F-C
  const MEL62=[['C7',0.00,0.15,'C'],['G6',0.16,0.15,'C'],
               ['A6',0.32,0.15,'F'],['F6',0.48,0.15,'F'],
               ['G6',0.64,0.15,'C'],['A6',0.80,0.15,'F'],['C7',0.96,0.50,'C']];
  const s62=()=>song(MEL62);

  // ── 音色アレンジ (62の音符・和声は固定 / 音作りだけ差し替え) ──────
  // tb: {lead,harm,bass=波形, vib=ビブラート, detune=デチューン量,
  //      endSparkle=最後にノイズ, bell=1oct上に三角を薄く重ねる, master}
  const songT=(mel,tb={})=>{
    const lead=tb.lead||'square', harm=tb.harm||'square', bassT=tb.bass||'triangle';
    const vib=tb.vib??0.008, det=tb.detune||0, N=mel.length;
    // 最後の音の長さ。lastDur 指定で伸ばせる(スタッカートでも末尾だけ伸ばす)
    const finalMd=tb.lastDur || (tb.stac ? Math.max(tb.stac,0.22) : mel[N-1][2]);
    const notes=[]; let last=null;
    mel.forEach(([n,t,d,ch],i)=>{
      const um=midiOf(n), isLast=i===N-1;
      const md=isLast ? finalMd : (tb.stac ? tb.stac : d);
      notes.push({f:fM(um),t,dur:md,type:lead,vol:0.55,vib});                        // 上声
      if(det) notes.push({f:fM(um)*(1+det),t,dur:md,type:lead,vol:0.38,vib});         // デチューン重ね(太く)
      notes.push({f:fM(snapTo(um-8,CHPC[ch])),t,dur:md,type:harm,vol:0.40,vib:vib*0.5}); // 下声
      if(tb.bell) notes.push({f:fM(um+12),t,dur:Math.min(md,isLast?0.4:0.12),type:'triangle',vol:0.15}); // 1oct上の薄いベル
      if(ch!==last){
        let end=mel[N-1][1]+finalMd, trailing=true;
        for(let j=i+1;j<N;j++){ if(mel[j][3]!==ch){ end=mel[j][1]; trailing=false; break; } }
        // ベース: 末尾の和音は伸ばした音に合わせて持続。途中はスタッカート時のみ短く
        const bd=(tb.stac && !trailing) ? Math.min(end-t, tb.stac+0.10) : end-t;
        notes.push({f:fM(nearBass(ROOTPC[ch],55)),t,dur:bd,type:bassT,vol:0.28});
        last=ch;
      }
    });
    if(tb.endSparkle){ const L=mel[N-1]; notes.push({noise:true,t:L[1],dur:0.14,vol:0.22}); }
    render(notes,{master:tb.master??0.2});
  };

